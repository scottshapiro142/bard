function typesFile(app: AppSpec): ScaffoldFile {
  const blocks: string[] = [];
  const unions: string[] = [];

  for (const entity of app.entities) {
    if (entity.fields.some((f) => f.type === "status")) {
      unions.push(
        `export type ${pascal(entity.name)}Status = ${statusValues(entity)
          .map((v) => `"${v}"`)
          .join(" | ")};`
      );
    }
    blocks.push(
      lines(
        `export interface ${pascal(entity.name)} {`,
        ...entity.fields.map(
          (field) =>
            `  ${field.name}${field.required ? "" : "?"}: ${tsTypeFor(field, entity.name)};`
        ),
        `}`
      )
    );
  }

  return {
    path: "lib/types.ts",
    language: "ts",
    because:
      "Exactly the fields you set in Screens. Change one there and this changes with it — the preview and this file read the same list, so they can't disagree.",
    contents: lines(
      `// Generated by Loom.`,
      `// What the app keeps: ${app.entities.map((e) => e.name).join(", ")}.`,
      ``,
      unions.join("\n"),
      unions.length ? `` : null,
      blocks.join("\n\n"),
      ``
    ),
  };
}

