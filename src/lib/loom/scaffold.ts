function buildPlan(brief: Brief, tasks: Task[]): ScaffoldFile {
  const out: string[] = [
    `# Build plan — ${brief.product || "Untitled"}`,
    ``,
    `**For:** ${brief.actorPlural}`,
    `**The one thing it must do:** ${brief.job || "—"}`,
    `**Tasks:** ${tasks.length}`,
    ``,
    `Generated by Loom. Ticked boxes are what you've marked done in the app.`,
    `Plain-language background for all of this is in \`docs/\`.`,
    ``,
  ];

  for (const milestone of MILESTONES) {
    const group = tasksIn(tasks, milestone.id);
    if (group.length === 0) continue;
    out.push(`## ${milestone.title} (${group.length})`, ``, milestone.blurb, ``);
    for (const task of group) {
      const flags = [task.size, task.from, task.severity].filter(Boolean);
      out.push(`- [ ] **${task.plain.what}** — \`${flags.join(" · ")}\``);
      out.push(`      ${task.plain.why}`);
      out.push(`      *Done when:* ${task.plain.done}`);
    }
    out.push(``);
  }

  out.push(
    `## Not in the first version`,
    ``,
    brief.outOfScope ||
      "Nothing has been ruled out. Worth naming three things before the first build meeting.",
    ``
  );

  return {
    path: "BUILD.md",
    language: "md",
    because:
      "The task list as a file, so it survives outside this browser and can sit in the repo next to the code.",
    contents: out.join("\n") + "\n",
  };
}

