/**
 * Generate a starting codebase.
 *
 * Not a finished app — the parts a review can actually determine: the types,
 * the storage seam, and the screens, each carrying the state the reviews found
 * missing. Where a review found an undecided question, the scaffold stops and
 * says so rather than picking for you.
 */
export function generateScaffold(
  brief: Brief,
  findings: Finding[],
  tasks: Task[]
): ScaffoldFile[] {
  const money = findings.some((f) => f.tags.includes("trust")) ||
    /pay|deposit|invoice|checkout|charge|billing/i.test(
      `${brief.job} ${brief.product}`
    );

  return [
    buildPlan(brief, tasks),
    typesFile(brief),
    dataFile(brief),
    listPage(brief),
    detailPage(brief),
    createPage(brief, money),
  ];
}

