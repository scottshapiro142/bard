export interface ScaffoldInput {
  brief: Brief;
  app: AppSpec;
  findings: Finding[];
  tasks: Task[];
  docs: DocPage[];
}

/**
 * The starting codebase.
 *
 * Not a finished app — the parts that can actually be worked out from your
 * answers. Where a review found an open question, the code stops and says so
 * rather than picking for you.
 */
export function generateScaffold(input: ScaffoldInput): ScaffoldFile[] {
  const { brief, app, findings, tasks, docs } = input;

  const money =
    findings.some((f) => f.tags.includes("trust")) ||
    /pay|deposit|invoice|checkout|charge|billing/i.test(
      `${brief.job} ${brief.product}`
    );

  const screens = enabledScreens(app);
  const usedEntityIds = new Set(
    screens.map((s) => s.entityId).filter((id): id is string => !!id)
  );
  const dataEntities = app.entities.filter((e) => usedEntityIds.has(e.id));
  const primary = primaryOf(app);

  const files: ScaffoldFile[] = [
    buildPlan(brief, tasks),
    {
      path: "app/globals.css",
      language: "css",
      because:
        "Your design system, as the standard shadcn setup. Every colour, corner and typeface on every screen comes from this one file.",
      contents: themeToCss(app.theme),
    },
    componentsJson(),
    typesFile(app),
    dataFile(app, dataEntities.length ? dataEntities : [primary]),
  ];

  for (const screen of screens) {
    const entity = app.entities.find((e) => e.id === screen.entityId);
    if (screen.kind === "list" && entity) files.push(listPage(screen, entity));
    else if (screen.kind === "detail" && entity) files.push(detailPage(screen, entity));
    else if (screen.kind === "create" && entity)
      files.push(createPage(screen, entity, money));
    else files.push(simplePage(screen));
  }

  for (const doc of docs) {
    files.push({
      path: doc.path,
      language: "md",
      because: doc.summary,
      contents: doc.body,
    });
  }

  return files;
}
