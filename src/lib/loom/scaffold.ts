function lines(...parts: (string | false | null | undefined)[]) {
  return parts.filter((p): p is string => typeof p === "string").join("\n");
}

/** `/shoots/[id]` -> `app/shoots/[id]/page.tsx` */
function pathFor(route: string): string {
  const clean = route.replace(/^\/+|\/+$/g, "");
  return clean ? `app/${clean}/page.tsx` : "app/page.tsx";
}

function labelFor(field: Field): string {
  return field.name
    .replace(/Id$/, "")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (c) => c.toUpperCase());
}

function statusValues(entity: EntitySpec): string[] {
  return /deposit|payment|invoice|order|fee|charge/i.test(entity.name)
    ? ["pending", "paid", "failed", "refunded"]
    : ["draft", "active", "archived"];
}

