function dataFile(app: AppSpec, entities: EntitySpec[]): ScaffoldFile {
  const parts: string[] = [
    `// Generated by Loom. Every screen reads and writes through this module.`,
    `// Replace the in-memory maps with your database; the screens don't change.`,
    ``,
    `import type { ${entities.map((e) => pascal(e.name)).join(", ")} } from "./types";`,
    ``,
  ];

  for (const entity of entities) {
    const Type = pascal(entity.name);
    const many = pascal(plural(entity.name));
    const store = camel(plural(entity.name));

    parts.push(
      lines(
        `const ${store} = new Map<string, ${Type}>();`,
        ``,
        `export async function list${many}(): Promise<${Type}[]> {`,
        `  return [...${store}.values()].sort((a, b) => b.createdAt - a.createdAt);`,
        `}`,
        ``,
        `export async function get${Type}(id: string): Promise<${Type} | null> {`,
        `  return ${store}.get(id) ?? null;`,
        `}`,
        ``,
        `export async function create${Type}(`,
        `  input: Omit<${Type}, "id" | "createdAt">`,
        `): Promise<${Type}> {`,
        `  const record: ${Type} = {`,
        `    ...input,`,
        `    id: crypto.randomUUID(),`,
        `    createdAt: Date.now(),`,
        `  };`,
        `  ${store}.set(record.id, record);`,
        `  return record;`,
        `}`,
        ``,
        `// TODO(loom): deletion is undefined — refuse while something still points`,
        `// at it, keep a marker where it was, or remove everything with it? Until`,
        `// that's decided this throws rather than guessing. See docs/04.`,
        `export async function remove${Type}(): Promise<never> {`,
        `  throw new Error("Deletion not decided yet — see docs/04-what-we-store.md");`,
        `}`,
        ``
      )
    );
  }

  return {
    path: "lib/data.ts",
    language: "ts",
    because:
      "One module in front of storage, so swapping in a real database is a one-file change. Deleting deliberately throws — that decision hasn't been made, and guessing at it is how data goes missing.",
    contents: parts.join("\n"),
  };
}

