function buildPlan(brief: Brief, tasks: Task[]): ScaffoldFile {
  const out: string[] = [
    `# Build plan — ${brief.product || "Untitled"}`,
    ``,
    `**For:** ${brief.actorPlural}`,
    `**Primary job:** ${brief.job || "—"}`,
    `**Tasks:** ${tasks.length}`,
    ``,
    `Generated by Loom from the reviews in this project. Checked boxes are what`,
    `you've marked done in the app.`,
    ``,
  ];

  for (const milestone of MILESTONES) {
    const group = tasksIn(tasks, milestone.id);
    if (group.length === 0) continue;
    out.push(`## ${milestone.title} (${group.length})`, ``, milestone.blurb, ``);
    for (const task of group) {
      const flags: string[] = [task.size];
      if (task.from) flags.push(task.from);
      if (task.severity) flags.push(task.severity);
      out.push(`- [ ] **${task.title}** — \`${flags.join(" · ")}\``);
      out.push(`      ${task.detail}`);
    }
    out.push(``);
  }

  out.push(
    `## Not in v1`,
    ``,
    brief.outOfScope ||
      "Nothing was declared out of scope. Name three things before the first build meeting.",
    ``
  );

  return {
    path: "BUILD.md",
    language: "md",
    because:
      "The task list as a file, so it survives outside this browser and can go in the repo next to the code.",
    contents: out.join("\n") + "\n",
  };
}

