function typesFile(brief: Brief): ScaffoldFile {
  const statusTypes = new Map<string, string[]>();
  const blocks: string[] = [];

  for (const entity of brief.entities) {
    const fields = fieldsFor(entity, brief);
    for (const [, type] of fields) {
      if (!type.endsWith("Status")) continue;
      if (type === "PaymentStatus") {
        statusTypes.set(type, ["pending", "paid", "failed", "refunded"]);
      } else {
        statusTypes.set(type, ["draft", "active", "archived"]);
      }
    }
    blocks.push(
      lines(
        `export interface ${pascal(entity)} {`,
        ...fields.map(([name, type]) => `  ${name}: ${type};`),
        `}`
      )
    );
  }

  return {
    path: "lib/types.ts",
    language: "ts",
    because:
      "Straight out of the data model review. The owner field on every non-identity record is there because that review flagged ownership as undecided.",
    contents: lines(
      `// Generated by Loom from the data model review.`,
      `// Entities named in the interview: ${brief.entities.join(", ")}.`,
      ``,
      ...[...statusTypes.entries()].map(
        ([name, values]) =>
          `export type ${name} = ${values.map((v) => `"${v}"`).join(" | ")};`
      ),
      statusTypes.size > 0 ? `` : null,
      blocks.join("\n\n"),
      ``
    ),
  };
}

