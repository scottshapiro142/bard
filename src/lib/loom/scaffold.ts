function listPage(screen: ScreenSpec, entity: EntitySpec): ScaffoldFile {
  const Type = pascal(entity.name);
  const many = pascal(plural(entity.name));
  const store = camel(plural(entity.name));
  const label = plural(entity.name);
  const one = entity.name.toLowerCase();
  const shown = displayField(entity)?.name ?? "id";

  return {
    path: pathFor(screen.route),
    language: "tsx",
    because:
      "The empty state is written before the populated one, because it's what every single person sees on their first visit.",
    contents: lines(
      `import Link from "next/link";`,
      ``,
      `import { list${many} } from "@/lib/data";`,
      `import type { ${Type} } from "@/lib/types";`,
      ``,
      `export default async function ${many}Page() {`,
      `  const ${store} = await list${many}();`,
      ``,
      `  // The most-seen version of the most-seen screen, written first on purpose.`,
      `  if (${store}.length === 0) {`,
      `    return (`,
      `      <main className="mx-auto max-w-2xl p-8">`,
      `        <h1 className="text-xl font-semibold tracking-tight">${label}</h1>`,
      `        <div className="mt-8 rounded-xl border border-dashed p-10 text-center">`,
      `          <p className="text-sm font-medium">No ${label.toLowerCase()} yet</p>`,
      `          <p className="mt-2 text-sm text-muted-foreground">`,
      `            {/* TODO(loom): this copy is the onboarding. Say what a ${one} is`,
      `                for, and what happens once they add the first one. */}`,
      `            Add your first ${one} to get started.`,
      `          </p>`,
      `          <Link`,
      `            href="${screen.route}/new"`,
      `            className="mt-4 inline-block rounded-md bg-primary px-3 py-1.5 text-sm text-primary-foreground"`,
      `          >`,
      `            Add a ${one}`,
      `          </Link>`,
      `        </div>`,
      `      </main>`,
      `    );`,
      `  }`,
      ``,
      `  return (`,
      `    <main className="mx-auto max-w-2xl p-8">`,
      `      <div className="flex items-center justify-between">`,
      `        <h1 className="text-xl font-semibold tracking-tight">${label}</h1>`,
      `        <Link href="${screen.route}/new" className="text-sm underline underline-offset-4">`,
      `          New ${one}`,
      `        </Link>`,
      `      </div>`,
      ``,
      `      {/* TODO(loom): past a few hundred records this needs search, sort and`,
      `          paging. Those change the screen rather than decorate it. */}`,
      `      <ul className="mt-6 divide-y rounded-xl border">`,
      `        {${store}.map((${camel(entity.name)}: ${Type}) => (`,
      `          <li key={${camel(entity.name)}.id}>`,
      `            <Link`,
      `              href={\`${screen.route}/\${${camel(entity.name)}.id}\`}`,
      `              className="block px-4 py-3 text-sm hover:bg-accent"`,
      `            >`,
      `              {${camel(entity.name)}.${shown}}`,
      `            </Link>`,
      `          </li>`,
      `        ))}`,
      `      </ul>`,
      `    </main>`,
      `  );`,
      `}`,
      ``
    ),
  };
}

function detailPage(screen: ScreenSpec, entity: EntitySpec): ScaffoldFile {
  const Type = pascal(entity.name);
  const record = camel(entity.name);
  const shown = displayField(entity)?.name ?? "id";
  const rest = entity.fields.filter((f) => f.name !== "id" && f.name !== shown);

  return {
    path: pathFor(screen.route),
    language: "tsx",
    because:
      "Stops at the permission question rather than guessing. Right now \"not found\" and \"you can't see this\" are the same answer, and which one you show is a decision.",
    contents: lines(
      `import { notFound } from "next/navigation";`,
      ``,
      `import { get${Type} } from "@/lib/data";`,
      ``,
      `// params is a promise in this version of Next.js.`,
      `export default async function ${Type}Page({`,
      `  params,`,
      `}: {`,
      `  params: Promise<{ id: string }>;`,
      `}) {`,
      `  const { id } = await params;`,
      `  const ${record} = await get${Type}(id);`,
      ``,
      `  // TODO(loom): "doesn't exist" and "isn't yours" are the same response`,
      `  // here. Collapsing them hides what exists, which may be what you want.`,
      `  // Decide on purpose, then delete this comment.`,
      `  if (!${record}) notFound();`,
      ``,
      `  return (`,
      `    <main className="mx-auto max-w-2xl p-8">`,
      `      <h1 className="text-xl font-semibold tracking-tight">{${record}.${shown}}</h1>`,
      `      <dl className="mt-6 overflow-hidden rounded-xl border">`,
      ...rest.map((field) =>
        lines(
          `        <div className="flex justify-between gap-4 border-b px-4 py-3 last:border-0">`,
          `          <dt className="text-sm text-muted-foreground">${labelFor(field)}</dt>`,
          `          <dd className="text-sm font-medium">{String(${record}.${field.name} ?? "—")}</dd>`,
          `        </div>`
        )
      ),
      `      </dl>`,
      `    </main>`,
      `  );`,
      `}`,
      ``
    ),
  };
}

function createPage(
  screen: ScreenSpec,
  entity: EntitySpec,
  money: boolean
): ScaffoldFile {
  const Type = pascal(entity.name);
  const editable = entity.fields.filter(
    (f) => !f.system && f.type !== "link" && f.type !== "status"
  );
  const first = editable[0];

  return {
    path: pathFor(screen.route),
    language: "tsx",
    because: money
      ? "Carries the three situations that matter once money is involved: saving, declined, and connection-lost-mid-payment. Those are not the same thing and must not look the same."
      : "Carries the failure path, not just the happy one. Saving and failing are states, not afterthoughts.",
    contents: lines(
      `"use client";`,
      ``,
      `import * as React from "react";`,
      `import { useRouter } from "next/navigation";`,
      ``,
      money
        ? `type Status = "idle" | "saving" | "declined" | "unknown" | "failed";`
        : `type Status = "idle" | "saving" | "failed";`,
      ``,
      `export default function New${Type}Page() {`,
      `  const router = useRouter();`,
      first ? `  const [value, setValue] = React.useState("");` : null,
      `  const [status, setStatus] = React.useState<Status>("idle");`,
      ``,
      `  async function submit(event: React.FormEvent) {`,
      `    event.preventDefault();`,
      `    if (status === "saving") return; // stops a double tap saving twice`,
      `    setStatus("saving");`,
      ``,
      `    try {`,
      `      const res = await fetch("/api${screen.route.replace(/\/new$/, "")}", {`,
      `        method: "POST",`,
      `        headers: { "Content-Type": "application/json" },`,
      first
        ? `        body: JSON.stringify({ ${first.name}: value }),`
        : `        body: "{}",`,
      `      });`,
      money
        ? lines(
            `      // A payment can go through after we've lost the answer. Treat that`,
            `      // as unknown, never as failed — telling someone it failed when it`,
            `      // didn't is how you get charged twice.`,
            `      if (res.status === 402) return setStatus("declined");`
          )
        : null,
      `      if (!res.ok) return setStatus("failed");`,
      `      router.push("${screen.route.replace(/\/new$/, "")}");`,
      `    } catch {`,
      money ? `      setStatus("unknown");` : `      setStatus("failed");`,
      `    }`,
      `  }`,
      ``,
      `  return (`,
      `    <main className="mx-auto max-w-md p-8">`,
      `      <h1 className="text-xl font-semibold tracking-tight">${screen.name}</h1>`,
      ``,
      `      <form onSubmit={submit} className="mt-6 space-y-4">`,
      first
        ? lines(
            `        <label className="block text-sm font-medium" htmlFor="${first.name}">`,
            `          ${labelFor(first)}`,
            `        </label>`,
            `        <input`,
            `          id="${first.name}"`,
            `          value={value}`,
            `          onChange={(e) => setValue(e.target.value)}`,
            `          required`,
            `          className="w-full rounded-md border px-3 py-2 text-sm"`,
            `        />`
          )
        : null,
      ``,
      `        <button`,
      `          type="submit"`,
      `          disabled={status === "saving"}`,
      `          className="w-full rounded-md bg-primary px-4 py-2 text-sm text-primary-foreground disabled:opacity-50"`,
      `        >`,
      `          {status === "saving" ? "Saving…" : "Save"}`,
      `        </button>`,
      `      </form>`,
      ``,
      `      {/* TODO(loom): this wording is a guess. It should say whether trying`,
      `          again would help. */}`,
      `      {status === "failed" ? (`,
      `        <p className="mt-4 text-sm text-destructive">`,
      `          That didn&apos;t save. Nothing was lost — try again.`,
      `        </p>`,
      `      ) : null}`,
      money
        ? lines(
            `      {status === "declined" ? (`,
            `        <p className="mt-4 text-sm text-destructive">`,
            `          The payment was declined. Nothing has been charged.`,
            `        </p>`,
            `      ) : null}`,
            `      {status === "unknown" ? (`,
            `        <p className="mt-4 text-sm text-muted-foreground">`,
            `          We lost the connection while this was going through. Don&apos;t try`,
            `          again yet — check your email for a confirmation first.`,
            `        </p>`,
            `      ) : null}`
          )
        : null,
      `    </main>`,
      `  );`,
      `}`,
      ``
    ),
  };
}

