function dataFile(brief: Brief): ScaffoldFile {
  const entity = primaryEntity(brief);
  const Type = pascal(entity);
  const many = pascal(plural(entity));
  const store = camel(plural(entity));

  return {
    path: "lib/data.ts",
    language: "ts",
    because:
      "One module in front of storage, so swapping the in-memory maps for a database is a one-file change. Deletion deliberately throws — the data model review found that decision hadn't been made.",
    contents: lines(
      `// Generated by Loom. Every screen reads and writes through this module.`,
      `// Replace the in-memory maps with your database; the screens don't change.`,
      ``,
      `import type { ${Type} } from "./types";`,
      ``,
      `const ${store} = new Map<string, ${Type}>();`,
      ``,
      `export async function list${many}(): Promise<${Type}[]> {`,
      `  return [...${store}.values()].sort((a, b) => b.createdAt - a.createdAt);`,
      `}`,
      ``,
      `export async function get${Type}(id: string): Promise<${Type} | null> {`,
      `  return ${store}.get(id) ?? null;`,
      `}`,
      ``,
      `export async function create${Type}(`,
      `  input: Omit<${Type}, "id" | "createdAt">`,
      `): Promise<${Type}> {`,
      `  const record: ${Type} = {`,
      `    ...input,`,
      `    id: crypto.randomUUID(),`,
      `    createdAt: Date.now(),`,
      `  };`,
      `  ${store}.set(record.id, record);`,
      `  return record;`,
      `}`,
      ``,
      `// TODO(loom): deletion is undefined — block while referenced, soft-delete`,
      `// and show a tombstone, or cascade? Until that's decided this throws`,
      `// rather than guessing. See data_model.md.`,
      `export async function remove${Type}(): Promise<never> {`,
      `  throw new Error("Deletion semantics undecided — see data_model.md");`,
      `}`,
      ``
    ),
  };
}

